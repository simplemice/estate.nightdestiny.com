/* ---------- css bundle (one render-blocking request instead of seven) ---------- */
function minCss(c) {
  return c.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{};,>])\s*/g, '$1').replace(/;}/g, '}').trim();
}
function buildCss() {
  const read = (f) => fs.readFileSync(path.join(ROOT, 'css', f), 'utf8');
  const parts = ['bootstrap.min.css', 'font-awesome.min.css', 'elegant-icons.css', 'slicknav.min.css', 'style.css', 'estate.css'];
  const css = parts.map((f) => (f.includes('.min.') ? read(f).replace(/\/\*[\s\S]*?\*\//g, '') : minCss(read(f)))).join('\n');
  return css.replace(/@font-face\s*\{/g, '@font-face{font-display:swap;');
}


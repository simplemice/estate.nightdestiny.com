function gallery(p, alt) {
  const all = [p.cover, ...p.images].filter((v, i, a) => v && a.indexOf(v) === i);
  const main = all[0];
  if (!main) return `<div class="estate-gallery"><div class="g-main g-none">${NOPHOTO()}<p>${T('no_photos')}</p></div></div>`;
  // Captions are written one per gallery image; older content lists them for the extra images only.
  const caps = (p.imageCaptions || []).map((c) => (LANG === DEFAULT_LANG ? c : I.tx(c, `${p.slug}:caption`)));
  const capOf = (i) => (caps.length >= all.length ? caps[i] : i > 0 ? caps[i - 1] : '');
  const seen = {};
  const altOf = (i) => {
    const c = String(capOf(i) || '').trim();
    if (!c) return i === 0 ? alt : T('alt.project_image', { name: p.name || '', area: areaName(areaOf(p.location)), n: i + 1 }).trim();
    let a = new RegExp(String(p.name || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i').test(c) ? c : T('alt.caption_at', { c, name: p.name || alt });
    seen[a] = (seen[a] || 0) + 1;
    return seen[a] > 1 ? `${a} (${seen[a]})` : a;
  };
  return `<div class="estate-gallery" data-gallery>
	<a class="g-main" href="${esc(bigSrc(main))}" data-full="${esc(bigSrc(main))}">${img(main, i0alt(p, alt, capOf(0)), { lazy: false, sizes: '(min-width: 992px) 66vw, 100vw' })}</a>
	${all.length > 1 ? `<div class="g-thumbs">${all.map((s, i) => `<a href="${esc(bigSrc(s))}" class="g-thumb${i === 0 ? ' active' : ''}" data-full="${esc(bigSrc(s))}" aria-label="${esc(T('image_n', { n: i + 1 }))}">${img(s, i === 0 ? i0alt(p, alt, capOf(0)) : altOf(i), { sizes: '120px' })}</a>`).join('')}</div>` : ''}
</div>`;
}

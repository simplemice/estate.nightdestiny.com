const AVAIL = ['Available', 'Reserved', 'Rented', 'Sold', 'Limited'];
function loadDir(dir, kind) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const rel = `${dir}/${f}`;
    let d;
    try { d = readJson(path.join(abs, f)); } catch (e) { err(rel, `invalid JSON (${e.message})`); return null; }
    d.slug = slugify(d.slug || f.replace(/\.json$/, ''));
    d._file = rel;
    d._kind = kind;
    return d;
  }).filter(Boolean);
}

const checkImages = (d, list) => list.forEach((p) => { if (p && !exists(p)) err(d._file, `image not found: ${p}`); });

function validateProperty(p, category) {
  const f = p._file;
  if (p.project) { // sale entry that points at a project (shown on the SALE page, details live on the project page)
    p.projectSlug = slugify(String(p.project).replace(/^.*\//, '').replace(/\.json$/, ''));
    if (!p.title) err(f, 'missing required field "title"');
    if (p.availability && !AVAIL.includes(p.availability)) err(f, `bad availability "${p.availability}"`);
    return;
  }
  ['title', 'propertyType', 'location'].forEach((k) => { if (!p[k]) err(f, `missing required field "${k}"`); });
  if (!(num(p.price) > 0)) err(f, 'price must be a number > 0');
  if (!p.cover) err(f, 'missing cover image');
  if (p.availability && !AVAIL.includes(p.availability)) err(f, `bad availability "${p.availability}"`);
  if (category === 'sale' && p.ownership && !['Freehold', 'Leasehold'].includes(p.ownership)) err(f, `bad ownership "${p.ownership}"`);
  if (!p.publishedAt || isNaN(Date.parse(p.publishedAt))) err(f, 'publishedAt must be a valid date');
  p.images = Array.isArray(p.images) ? p.images : [];
  checkImages(p, [p.cover, ...p.images]);
}
function validateProject(p) {
  const f = p._file;
  ['name', 'location', 'projectType', 'constructionStatus'].forEach((k) => { if (!p[k]) err(f, `missing required field "${k}"`); });
  if (!p.cover && p.imagesStatus !== 'unavailable') err(f, 'missing cover image (or set imagesStatus to "unavailable")');
  if (p.startingPrice !== undefined && p.startingPrice !== null && p.startingPrice !== '' && !(num(p.startingPrice) >= 0)) err(f, 'startingPrice must be a number');
  p.category = p.category || (p.projectType === 'Villas' ? 'Villa' : 'Condominium');
  if (!['Villa', 'Townhouse', 'Condominium'].includes(p.category)) err(f, `bad category "${p.category}"`);
  p.ownership = Array.isArray(p.ownership) ? p.ownership : [];
  p.ownership.forEach((o) => { if (!['Freehold', 'Leasehold'].includes(o)) err(f, `bad ownership "${o}"`); });
  p.sources = Array.isArray(p.sources) ? p.sources : [];
  p.paymentPlan = Array.isArray(p.paymentPlan) ? p.paymentPlan : [];
  p.sources.forEach((x, i) => { if (!/^https?:\/\//.test(x.url || '')) err(f, `sources[${i}].url must be http(s)`); });
  p.images = Array.isArray(p.images) ? p.images : [];
  p.floorPlans = Array.isArray(p.floorPlans) ? p.floorPlans : [];
  p.unitTypes = Array.isArray(p.unitTypes) ? p.unitTypes : [];
  p.unitTypes.forEach((u, i) => { if (!u.name) err(f, `unitTypes[${i}] missing name`); });
  checkImages(p, [p.cover, ...p.images, ...p.floorPlans, ...p.unitTypes.map((u) => u.floorPlan)].filter(Boolean));
}


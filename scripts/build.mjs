// Optimized variants live in /assets/optimized/<path-without-ext>-<w>.webp (made by scripts/optimize-images.mjs)
const WIDTHS = [480, 800, 1280, 1920];
function variants(src) {
  const base = '/assets/optimized/' + src.replace(/^\//, '').replace(/\.[a-z0-9]+$/i, '');
  const found = WIDTHS.filter((w) => exists(`${base}-${w}.webp`));
  return { base, found };
}
function img(src, alt, { sizes = '(min-width: 992px) 33vw, 100vw', lazy = true, cls = '' } = {}) {
  const { base, found } = variants(src);
  const attrs = `alt="${esc(alt)}"${lazy ? ' loading="lazy" decoding="async"' : ''}${cls ? ` class="${cls}"` : ''}`;
  if (!found.length) return `<img src="${esc(src)}" ${attrs}>`;
  const srcset = found.map((w) => `${base}-${w}.webp ${w}w`).join(', ');
  return `<picture><source type="image/webp" srcset="${esc(srcset)}" sizes="${sizes}"><img src="${esc(src)}" ${attrs}></picture>`;
}
const bigSrc = (src) => {
  const { base, found } = variants(src);
  return found.length ? `${base}-${found[found.length - 1]}.webp` : src;
};

/* ---------- load + validate content ---------- */
const errors = [];
const warn = [];
const err = (f, m) => errors.push(`${f}: ${m}`);

const AVAIL = ['Available', 'Reserved', 'Rented', 'Sold', 'Limited'];
function loadDir(dir, kind) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const rel = `${dir}/${f}`;
    let d;
    try { d = readJson(path.join(abs, f)); } catch (e) { err(rel, `invalid JSON (${e.message})`); return null; }
    d.slug = slugify(d.slug || f.replace(/\.json$/, ''));
    d._file = rel;
    d._kind = kind;
    return d;
  }).filter(Boolean);
}

const checkImages = (d, list) => list.forEach((p) => { if (p && !exists(p)) err(d._file, `image not found: ${p}`); });

function validateProperty(p, category) {
  const f = p._file;
  if (p.project) { // sale entry that points at a project (shown on the SALE page, details live on the project page)
    p.projectSlug = slugify(String(p.project).replace(/^.*\//, '').replace(/\.json$/, ''));
    if (!p.title) err(f, 'missing required field "title"');
    if (p.availability && !AVAIL.includes(p.availability)) err(f, `bad availability "${p.availability}"`);
    return;
  }
  ['title', 'propertyType', 'location'].forEach((k) => { if (!p[k]) err(f, `missing required field "${k}"`); });
  if (!(num(p.price) > 0)) err(f, 'price must be a number > 0');
  if (!p.cover) err(f, 'missing cover image');
  if (p.availability && !AVAIL.includes(p.availability)) err(f, `bad availability "${p.availability}"`);
  if (category === 'sale' && p.ownership && !['Freehold', 'Leasehold'].includes(p.ownership)) err(f, `bad ownership "${p.ownership}"`);
  if (!p.publishedAt || isNaN(Date.parse(p.publishedAt))) err(f, 'publishedAt must be a valid date');
  p.images = Array.isArray(p.images) ? p.images : [];
  checkImages(p, [p.cover, ...p.images]);
}
function validateProject(p) {
  const f = p._file;
  ['name', 'location', 'projectType', 'constructionStatus'].forEach((k) => { if (!p[k]) err(f, `missing required field "${k}"`); });
  if (!p.cover) err(f, 'missing cover image');
  if (p.startingPrice !== undefined && p.startingPrice !== '' && !(num(p.startingPrice) >= 0)) err(f, 'startingPrice must be a number');
  p.images = Array.isArray(p.images) ? p.images : [];
  p.floorPlans = Array.isArray(p.floorPlans) ? p.floorPlans : [];
  p.unitTypes = Array.isArray(p.unitTypes) ? p.unitTypes : [];
  p.unitTypes.forEach((u, i) => { if (!u.name) err(f, `unitTypes[${i}] missing name`); });
  checkImages(p, [p.cover, ...p.images, ...p.floorPlans, ...p.unitTypes.map((u) => u.floorPlan)]);
}

const rent = loadDir('content/properties/rent', 'rent');
const sale = loadDir('content/properties/sale', 'sale');
const projectsAll = loadDir('content/projects', 'project');
rent.forEach((p) => { p.category = 'rent'; validateProperty(p, 'rent'); });
sale.forEach((p) => { p.category = 'sale'; validateProperty(p, 'sale'); });
projectsAll.forEach(validateProject);
for (const [name, list] of [['rent', rent], ['sale', sale], ['projects', projectsAll]]) {
  const seen = new Set();
  list.forEach((p) => { if (seen.has(p.slug)) err(p._file, `duplicate slug "${p.slug}"`); seen.add(p.slug); });
}
if (!/^\d{8,15}$/.test(WA)) err('content/settings.json', 'whatsappNumber must be digits only with country code, no "+"');

if (errors.length) {
  console.error('CONTENT VALIDATION FAILED:\n  ' + errors.join('\n  '));
  process.exit(1);
}
const projBySlug = new Map(projectsAll.map((x) => [x.slug, x]));
sale.filter((p) => p.projectSlug && !projBySlug.has(p.projectSlug)).forEach((p) => err(p._file, `linked project "${p.projectSlug}" not found`));
if (errors.length) { console.error('CONTENT VALIDATION FAILED:\n  ' + errors.join('\n  ')); process.exit(1); }
const byNewest = (a, b) => Date.parse(b.publishedAt || 0) - Date.parse(a.publishedAt || 0);
const live = (a) => a.filter((p) => p.published !== false);
const rentL = live(rent).sort(byNewest);
const projL0 = live(projectsAll).sort(byNewest);
const saleAll = live(sale).sort(byNewest);
const saleL = saleAll.filter((p) => !p.projectSlug);                       // normal sale properties (own detail pages)
const saleProjects = saleAll.filter((p) => p.projectSlug && projBySlug.get(p.projectSlug)?.published !== false)
  .map((e) => ({ ...projBySlug.get(e.projectSlug), _saleEntry: e }));      // projects listed on SALE
const projL = projL0;
console.log(`Content OK: ${rentL.length} rent, ${saleL.length} sale (+${saleProjects.length} linked projects), ${projL.length} projects (${rent.length + sale.length + projectsAll.length - rentL.length - saleAll.length - projL.length} unpublished)`);
if (CHECK) process.exit(0);


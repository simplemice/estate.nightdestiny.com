function img(src, alt, { sizes = '(min-width: 992px) 33vw, 100vw', lazy = true, cls = '', priority = false } = {}) {
  const { base, found } = variants(src);
  const dm = DIMS[src] ? ` width="${DIMS[src][0]}" height="${DIMS[src][1]}"` : '';
  const attrs = `alt="${esc(alt)}"${dm}${lazy ? ' loading="lazy" decoding="async"' : ''}${priority ? ' fetchpriority="high"' : ''}${cls ? ` class="${cls}"` : ''}`;
  if (!found.length) return `<img src="${esc(src)}" ${attrs}>`;
  const srcset = found.map((w) => `${base}-${w}.webp ${w}w`).join(', ');
  return `<picture><source type="image/webp" srcset="${esc(srcset)}" sizes="${sizes}"><img src="${esc(src)}" ${attrs}></picture>`;
}

function money(v, cur = 'THB') {
  const n = num(v);
  if (n === null) return '';
  return cur === 'THB' ? `฿${fmtNum(n)}` : cur === 'USD' ? `$${fmtNum(n)}` : `${fmtNum(n)} ${cur}`;
}

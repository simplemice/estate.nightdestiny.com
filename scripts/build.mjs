const spec = (k, v) => (v === undefined || v === null || v === '' ? '' : `<tr><td class="r-o">${esc(k)}</td><td>${esc(v)}</td></tr>`);
const list_ = (arr, cls = '') => (arr?.length ? `<ul class="check-list ${cls}">${arr.map((x) => `<li><i class="fa fa-check"></i> ${esc(x)}</li>`).join('')}</ul>` : '');

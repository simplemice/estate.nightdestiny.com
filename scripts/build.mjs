function mapBlock(c, label) {
  const lat = num(c?.lat), lng = num(c?.lng);
  if (lat === null || lng === null || isNaN(lat) || isNaN(lng)) return '';
  const d = 0.008;
  const bbox = [lng - d, lat - d, lng + d, lat + d].join('%2C');
  return `<h4 class="sec-h">Location</h4><div class="map-wrap"><iframe title="Map: ${esc(label)}" loading="lazy" referrerpolicy="no-referrer" src="https://www.openstreetmap.org/export/embed.html?bbox=${bbox}&amp;layer=mapnik&amp;marker=${lat}%2C${lng}"></iframe></div><p class="map-link"><a href="https://www.openstreetmap.org/?mlat=${lat}&amp;mlon=${lng}#map=15/${lat}/${lng}" target="_blank" rel="noopener">Open larger map</a></p>`;
}

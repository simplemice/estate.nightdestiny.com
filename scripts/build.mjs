const pub = (p) => ({ slug: p.slug, url: url(p), kind: p._kind === 'project' ? 'project' : p.category, title: title(p), location: p.location, type: p.propertyType || p.projectType, price: num(p.price ?? p.startingPrice), currency: p.currency || 'THB', cover: p.cover, publishedAt: p.publishedAt, featured: !!p.featured });
write('data/listings.json', JSON.stringify({ generatedFrom: 'content/', rent: rentL.map(pub), sale: saleL.map(pub), projects: projL.map(pub) }, null, 1));

// full static catalogue data for the projects (public fields only)
const pubProject = (p) => { const f = facts(p); return { id: p.slug, name: p.name, url: url(p), category: p.category, propertyType: p.projectType, developer: p.developer ?? null, location: p.location, startingPrice: f.price, currency: p.currency || 'THB', priceStatus: f.price ? (p.priceStatus || 'advertised') : 'on-request', bedrooms: [f.bedMin, f.bedMax], bathrooms: [f.bathMin, f.bathMax], builtUpArea: [f.sizeMin, f.sizeMax], status: p.constructionStatus, completionDate: p.completionDate ?? null, cover: p.cover, imageCount: 1 + p.images.length, lastVerified: p.lastVerified ?? null }; };
write('data/projects.json', JSON.stringify(projL.map(pubProject), null, 1));
write('data/developers.json', JSON.stringify([...new Set(projL.map((p) => p.developer).filter(Boolean))].sort().map((d) => ({ name: d, projects: projL.filter((p) => p.developer === d).map((p) => p.slug) })), null, 1));
write('data/locations.json', JSON.stringify([...new Set(projL.map((p) => p.location))].sort().map((l) => ({ name: l, projects: projL.filter((p) => p.location === l).map((p) => p.slug) })), null, 1));

// sitemap: real lastmod from content dates, image entries, change frequency. ?page=N and filter URLs are intentionally excluded.
// Every URL is listed once per language, each with xhtml:link alternates (en, ru, x-default) pointing at the equivalent pages.
const xesc = (v) => String(v).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]));
const dOf = (p) => dateFmt(p.lastVerified) || dateFmt(p.publishedAt) || today;
const latest = (arr) => arr.map(dOf).sort().pop() || today;
const today = new Date().toISOString().slice(0, 10);
const locMod = (g) => latest(g.projects); // content dates only: file mtimes differ between local and CI checkouts and caused sitemap.xml conflicts
const allListings = rentL.concat(saleL, projL);
const guideMod = (g) => LANGS.map((l) => (LOCALES[l].over.guides[g] || {}).modified).filter(Boolean).sort().pop() || today;
const imgsOf = (p) => [p.cover, ...(p.images || [])].filter(Boolean).filter((v, i, a) => a.indexOf(v) === i).slice(0, 9);
const entry = (loc, lastmod, changefreq, priority, p, only) => (only || readyLangs(p)).map((l, _i, all) => `<url><loc>${SITE}${lpFor(l, loc)}</loc><lastmod>${lastmod}</lastmod><changefreq>${changefreq}</changefreq><priority>${priority}</priority>${all.length > 1 ? `${all.map((a) => `<xhtml:link rel="alternate" hreflang="${LANG_META[a].hreflang}" href="${SITE}${lpFor(a, loc)}"/>`).join('')}<xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${lpFor(DEFAULT_LANG, loc)}"/>` : ''}${p ? imgsOf(p).map((i, n) => `<image:image><image:loc>${xesc(SITE + i)}</image:loc><image:title>${xesc(`${title(p)}${n ? ' - photo ' + (n + 1) : ''}`)}</image:title></image:image>`).join('') : ''}</url>`).join('\n');
const urls = [
  ['/', latest(allListings), 'weekly', '1.0'],
  ['/rent/', latest(rentL), 'weekly', '0.9'],
  ['/sale/', latest(saleAll.length ? saleAll.concat(saleL) : saleL), 'weekly', '0.9'],
  ['/projects/', latest(projL.filter((x) => !facts(x).price)), 'weekly', '0.9'],
  ['/locations/', [...LOCS.map(locMod), ...OTHER_LOCS.map((g) => latest(g.projects))].sort().pop(), 'weekly', '0.8'],
  ...LOCS.map((g) => [g.url, locMod(g), 'weekly', '0.8']),
  ['/about/', latest(allListings), 'yearly', '0.4'],
  ['/contact/', latest(allListings), 'yearly', '0.5'],
  ['/guides/', LANGS.map((l) => Object.values(LOCALES[l].over.guides).map((x) => x.modified).filter(Boolean)).flat().sort().pop() || today, 'monthly', '0.6', null, LANGS.filter((l) => Object.keys(LOCALES[l].over.guides).length)],
  ...[...new Set(LANGS.flatMap((l) => Object.keys(LOCALES[l].over.guides)))].map((g) => [`/guides/${g}/`, guideMod(g), 'monthly', '0.6', null, guideLangs(g)]),
  ...rentL.concat(saleL).map((x) => [urlN(x), dOf(x), 'weekly', '0.7', x]),
  ...projL.filter((x) => x.noindex !== true).map((x) => [urlN(x), dOf(x), 'weekly', '0.8', x]),
];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.map(([u, lm, cf, pr, p, only]) => entry(u, lm, cf, pr, p, only)).join('\n')}\n</urlset>\n`);

// Translation coverage: English text that was shown on a non-English page because no translation exists yet.
const gaps = LANGS.filter((l) => l !== DEFAULT_LANG).map((l) => [l, LOCALES[l].missing]).filter(([, m]) => m.size);
if (gaps.length) {
  for (const [l, m] of gaps) {
    console.warn(`i18n [${l}]: ${m.size} untranslated phrase(s) shown in English`);
    if (process.argv.includes('--missing')) [...m].forEach(([k, w]) => console.warn(`  ${w}: ${k}`));
  }
  if (process.argv.includes('--strict')) process.exit(1);
}
const ruDrafts = [...projL, ...rentL].filter((p) => !langReady('ru', p));
if (ruDrafts.length) console.warn(`i18n [ru]: ${ruDrafts.length} page(s) await translation review (noindex, no hreflang, not in sitemap): ${ruDrafts.map((p) => p.slug).join(', ')}`);
console.log(`${CHECK ? 'Checked' : 'Built'} ${written.size} files (${urls.length} URLs x ${LANGS.length} languages in the sitemap).`);
